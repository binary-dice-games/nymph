/// @file theme_catalog.hpp
/// @brief Chart themes: named sets of field values that a source picks with
///        `image.theme` and that fill every field the source leaves out
///        (docs/themes.md, spec/01_core_features/DESIGN.md section 3,
///        "Themes").
///
/// A theme is a YAML file of `resources/themes/`, compiled in by
/// `cmake/NymphThemes.cmake`:
///
///     name: Ocean                 # shown in pickers
///     description: ...            # one sentence
///     base: dark                  # ImGui / ImPlot / ImUml colours under it
///     image: {background: "#0f2233", palette: [...], font: ..., ...}
///     fields:
///       text_color: "#dce6f0"     # every element (text style: the image's)
///       uml:fill_color: "#16324a" # elements of slot uml or uml.<anything>
///       FlowNode:fill_color: ...  # one element type (any letter case)
///
/// The most specific rule wins: a type, then the longest slot prefix, then
/// the bare field name. A value the source writes always wins, on the
/// element or on an enclosing one (text style and colours inherit).
#pragma once

#include <map>
#include <span>
#include <string>
#include <string_view>
#include <vector>
#include "document/yaml_doc.hpp"
#include "fonts/embedded_fonts.hpp"

namespace bdg::nymph {

class element_class;
class registry;

/// @brief The theme files compiled in (themes/*.yaml), by name without the
///        extension, sorted by name. Generated by cmake/NymphThemes.cmake.
std::span<const embedded_file> embedded_themes();

/// @brief One entry of a theme's `fields`: `[qualifier:]field: value`.
struct theme_rule {
  /// "" for every element; else a type name or a slot prefix, in lower
  /// case ("flownode", "uml", "plot2d.item").
  std::string qualifier;
  std::string key; ///< The key as written ("FlowNode:fill_color"), for messages.
  yaml_node value;
};

/// @brief One theme.
struct chart_theme {
  std::string id; ///< File name without `.yaml`: what `image.theme` takes.
  std::string name; ///< Display name ("Ocean").
  std::string description;
  std::string base; ///< "light", "dark" or "classic".
  /// Defaults for the `image` options the source leaves out (padding,
  /// font, font_size, text_color, background, palette), as written.
  std::vector<std::pair<std::string, yaml_node>> image;
  /// The `fields` rules by field name, in file order.
  std::map<std::string, std::vector<theme_rule>, std::less<>> rules;

  // ── For pickers (swatches) ──
  bool dark = false; ///< Whether its background is dark.
  std::string background; ///< "#RRGGBB": the figure's background.
  std::string text_color; ///< "#RRGGBB": its text.
  std::vector<std::string> palette; ///< Its series colours, "#RRGGBB[AA]".

  /// @brief The most specific rule for field `field` of an element of
  ///        class `cls`, or nullptr. `bare` false skips rules without a
  ///        qualifier (bind applies the text style ones to the image).
  const theme_rule* rule_for(const element_class& cls, std::string_view field, bool bare = true) const;

  /// @brief The value the theme gives image option `key`, or nullptr.
  const yaml_node* image_value(std::string_view key) const;
};

/// @brief The image options a theme may set.
inline constexpr std::string_view kThemeImageKeys[] =
    {"padding", "font", "font_size", "text_color", "background", "palette"};

/// @brief Parses one theme file.
/// @throws nymph::error, positioned in the file, for a malformed theme
///         (keys, base, image options, rule keys); field values are
///         checked by check_chart_theme().
chart_theme parse_chart_theme(std::string id, std::string_view yaml);

/// @brief Every built-in theme: light, dark and classic first, then the
///        others by name. Parsed once per process.
std::span<const chart_theme> chart_themes();

/// @brief The built-in theme `id`, or nullptr.
const chart_theme* find_chart_theme(std::string_view id);

/// @brief "light, dark, classic, forest, ...": every theme id.
std::string chart_theme_list();

/// @brief Every theme as a JSON array, for pickers in web pages:
///        `[{"id","name","description","base","dark","background",
///        "text_color","palette":[...]}]`.
std::string chart_themes_json();

/// @brief Checks every rule of `t` against `reg`: its qualifier names a
///        type or a slot prefix, some class it covers has the field, and
///        the value converts for each of them.
/// @return The problems found, one per line; empty when the theme is fine.
std::vector<std::string> check_chart_theme(const chart_theme& t, const registry& reg);

} // namespace bdg::nymph
