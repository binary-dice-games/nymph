/// @file placeholders.hpp
/// @brief The built-in placeholder images that `Image` and `ImageButton`
///        name (spec/09_ui_mockups/DESIGN.md section 3, "Placeholder
///        images"): vector shapes drawn with ImDrawList in one tint on one
///        background.
#pragma once

#include <imgui.h>
#include <span>
#include <string>
#include <string_view>
#include <vector>
#include "fonts/embedded_fonts.hpp"
#include "placeholders/svg_shapes.hpp"

namespace bdg::nymph {

/// @brief The placeholder files compiled in (placeholders/*.svg), by name
///        without the extension, sorted. Generated by
///        cmake/NymphPlaceholders.cmake.
std::span<const embedded_file> embedded_placeholders();

/// @brief Every placeholder name, sorted ("building", "chart", ...).
std::vector<std::string> placeholder_names();

/// @brief The parsed placeholder `name` (parsed once per process,
///        thread-safe), or nullptr for an unknown name.
/// @throws svg_error if the embedded file breaks the subset (a build
///         error the placeholder tests catch first).
const svg_image* find_placeholder(std::string_view name);

/// @brief How a placeholder fills its box.
enum class placeholder_fit {
  contain, ///< Keeps the aspect ratio, centred, whole image visible.
  cover, ///< Keeps the aspect ratio, fills the box, clipped to it.
  stretch, ///< Fills the box in both directions.
};

/// @brief How to draw one placeholder.
struct placeholder_style {
  placeholder_fit fit = placeholder_fit::contain;
  ImU32 tint = 0; ///< Colour of the shapes.
  ImU32 background = 0; ///< Colour of the box and the cut-outs; 0 alpha for none.
  /// Colour behind the box (the window's), used for cut-outs and corners
  /// when the background is transparent.
  ImU32 behind = 0;
  float rounding = 0.0f; ///< Corner radius of the box; the corners outside it are painted `behind`.
  bool border = false; ///< Outlines the box in the theme's border colour.
};

/// @brief Draws placeholder `image` into [`min`, `max`) on `dl`.
void draw_placeholder(ImDrawList* dl, const svg_image& image, ImVec2 min, ImVec2 max, const placeholder_style& style);

} // namespace bdg::nymph
